_ALIASES = {"grcm38": "mm10", "mm10": "mm10", "grch38": "hg38", "hg38": "hg38"}


def chromosome_folds(genome: str, fold: int = 0) -> Dict[str, List[str]]:
    """scPrinter's train/valid/test chromosomes for ``genome`` (mm10 or
    hg38, or their GRC names) and ``fold`` (0-4)."""
    key = _ALIASES.get(str(genome).lower())
    if key is None:
        raise KeyError(f"no scPrinter folds for {genome!r}; have mm10 and hg38")
    if not 0 <= fold < 5:
        raise ValueError("fold must be 0..4")
    return {k: list(v) for k, v in FOLDS[key][fold].items()}
