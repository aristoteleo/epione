# set.seed(21); runif(5)
RUNIF21 = [ 0.78611492714844644, 0.25244559557177126, 0.6992523034568876, 0.18446075334213674, 0.95961382566019893 ]
# set.seed(21); .Random.seed[1:4]
SEED21_HEAD = [ 10403, 624, 894178689, -1601845938 ]


def test_r_runif_bit_identical():
    assert np.array_equal(RRandom(21).unif_rand(5), np.array(RUNIF21))
    assert RRandom(21).unif_rand() == RUNIF21[0]


def test_r_random_seed_state():
    assert list(RRandom(21).random_seed()[:4]) == SEED21_HEAD


def test_cov_sde_matches_covrob():
    center, cov = cov_sde(np.array(X))
    assert np.array_equal(center, np.array(CENTER))
    np.testing.assert_allclose(cov, np.array(COV), rtol=1e-13, atol=0)


def test_cov_sde_details():
    center, cov, det = cov_sde(np.array(X), return_details=True)
    assert det["nresper"] == 1000
    w = det["weights"]
    assert w.shape == (40,) and np.all((w >= 0) & (w <= 1))
    # the four shifted rows get zero weight; most of the rest keep full weight
    assert np.all(w[:4] == 0)
    assert np.mean(w[4:] == 1) > 0.6


def test_cov_sde_drops_nonfinite_rows():
    x = np.array(X)
    xn = np.vstack([x, [np.nan, 0.0, 0.0]])
    c1, s1 = cov_sde(x)
    c2, s2 = cov_sde(xn)
    assert np.array_equal(c1, c2) and np.array_equal(s1, s2)


def test_cov_sde_input_checks():
    with pytest.raises(ValueError):
        cov_sde(np.ones((10, 1)))
    with pytest.raises(ValueError):
        cov_sde(np.random.default_rng(0).normal(size=(4, 3)))
    with pytest.raises(ValueError):
        cov_sde(np.array(X), seed=None)
